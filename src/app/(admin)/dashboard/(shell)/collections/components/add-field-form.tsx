'use client';

import { useTranslations } from 'next-intl';
import { useRouter } from 'next/navigation';
import { z } from 'zod';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { Button } from '@/components/ui/button';
import { Checkbox } from '@/components/ui/checkbox';
import { FormInput as Input } from '@/components/ui/input';
import { Switch } from '@/components/ui/switch';
import { Textarea } from '@/components/ui/textarea';
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select';
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from '@/components/ui/form';
import { fieldKeyFromLabel } from '@/config/post-types';
import { addCollectionField } from '../_modules/collections.actions';
import {
  collectionFieldSchema,
  FIELD_TYPES,
} from '../_modules/collections.schemas';
import { objectToFormData } from '../_modules/form-helpers';
import { TextModeSwitches, UrlModeSwitches } from './field-mode-switches';
import { useFormAction } from '@/hooks/use-form-action';

type CollectionFieldInput = z.input<typeof collectionFieldSchema>;

interface AddFieldFormProps {
  collectionId: string;
  /** Other post types a relation field can point at. */
  postTypes: { id: string; name: string }[];
}

const DEFAULTS: CollectionFieldInput = {
  label: '',
  key: '',
  type: 'text',
  required: false,
  choices: '',
  relationCollectionId: '',
  multiple: false,
  isFeatured: false,
  textMode: 'plain',
  urlMode: 'other',
};

export function AddFieldForm({ collectionId, postTypes }: AddFieldFormProps) {
  const t = useTranslations('collections.fieldForm');
  const tTypes = useTranslations('collections.fieldTypes');
  const router = useRouter();
  const form = useForm<CollectionFieldInput>({
    resolver: zodResolver(collectionFieldSchema),
    defaultValues: DEFAULTS,
  });
  const type = form.watch('type');
  const multiple = form.watch('multiple');
  const isFeatured = form.watch('isFeatured');
  const textMode = form.watch('textMode') ?? 'plain';
  const urlMode = form.watch('urlMode') ?? 'other';

  const { submit, isPending, error } = useFormAction(addCollectionField, {
    onSuccess: () => {
      form.reset(DEFAULTS);
      router.refresh();
    },
  });

  const onSubmit = (data: CollectionFieldInput) => {
    const featured = data.type === 'media' && Boolean(data.isFeatured);
    const multi = data.type === 'media' && !featured && Boolean(data.multiple);
    submit(
      objectToFormData({
        collectionId,
        ...data,
        required: data.required ? 'on' : 'off',
        multiple: multi ? 'on' : 'off',
        isFeatured: featured ? 'on' : 'off',
        textMode: data.type === 'text' ? (data.textMode ?? 'plain') : 'plain',
        urlMode: data.type === 'url' ? (data.urlMode ?? 'other') : 'other',
      })
    );
  };

  return (
    <Form {...form}>
      <form
        onSubmit={form.handleSubmit(onSubmit)}
        className="grid gap-3 sm:grid-cols-2"
      >
        <FormField
          control={form.control}
          name="label"
          render={({ field }) => (
            <FormItem>
              <FormLabel>{t('label')}</FormLabel>
              <FormControl>
                <Input
                  {...field}
                  required
                  placeholder={t('labelPlaceholder')}
                  onChange={e => {
                    field.onChange(e);
                    form.setValue('key', fieldKeyFromLabel(e.target.value));
                  }}
                />
              </FormControl>
              <FormMessage />
            </FormItem>
          )}
        />
        <FormField
          control={form.control}
          name="key"
          render={({ field }) => (
            <FormItem>
              <FormLabel className="flex items-center justify-between">
                <span>{t('key')}</span>
                <span className="text-xs font-normal text-muted-foreground">
                  {t('autoGenerated')}
                </span>
              </FormLabel>
              <FormControl>
                <Input
                  {...field}
                  value={field.value ?? ''}
                  placeholder="job_title"
                  className="bg-muted/50 font-mono text-xs"
                />
              </FormControl>
              <FormMessage />
            </FormItem>
          )}
        />
        <FormField
          control={form.control}
          name="type"
          render={({ field }) => (
            <FormItem>
              <FormLabel>{t('type')}</FormLabel>
              <Select
                value={field.value}
                onValueChange={value =>
                  field.onChange(value as CollectionFieldInput['type'])
                }
              >
                <FormControl>
                  <SelectTrigger className="w-full">
                    <SelectValue placeholder={t('selectType')} />
                  </SelectTrigger>
                </FormControl>
                <SelectContent>
                  {FIELD_TYPES.map(option => (
                    <SelectItem key={option.value} value={option.value}>
                      {tTypes(`${option.value}.label`)}
                      <span className="ms-2 text-xs text-muted-foreground">
                        {tTypes(`${option.value}.hint`)}
                      </span>
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
              <FormMessage />
            </FormItem>
          )}
        />
        <FormField
          control={form.control}
          name="required"
          render={({ field }) => (
            <FormItem className="flex items-center gap-2 self-end pb-2">
              <FormControl>
                <Checkbox
                  checked={field.value === true}
                  onCheckedChange={value => field.onChange(value === true)}
                />
              </FormControl>
              <FormLabel className="font-normal">{t('required')}</FormLabel>
            </FormItem>
          )}
        />
        {type === 'media' && (
          <div className="sm:col-span-2 flex flex-wrap items-center gap-6 rounded-md border border-dashed px-3 py-2.5 bg-muted/20">
            <FormField
              control={form.control}
              name="multiple"
              render={({ field }) => (
                <FormItem className="flex items-center gap-2.5 space-y-0">
                  <FormControl>
                    <Switch
                      checked={!isFeatured && field.value === true}
                      disabled={isFeatured === true}
                      onChange={value => {
                        const checked = value === true;
                        field.onChange(checked);
                        if (checked) form.setValue('isFeatured', false);
                      }}
                    />
                  </FormControl>
                  <FormLabel
                    className={
                      isFeatured
                        ? 'font-normal text-muted-foreground cursor-not-allowed'
                        : 'font-normal cursor-pointer'
                    }
                  >
                    {t('multipleImages')}
                  </FormLabel>
                </FormItem>
              )}
            />
            <FormField
              control={form.control}
              name="isFeatured"
              render={({ field }) => (
                <FormItem className="flex items-center gap-2.5 space-y-0">
                  <FormControl>
                    <Switch
                      checked={!multiple && field.value === true}
                      disabled={multiple === true}
                      onChange={value => {
                        const checked = value === true;
                        field.onChange(checked);
                        if (checked) form.setValue('multiple', false);
                      }}
                    />
                  </FormControl>
                  <FormLabel
                    className={
                      multiple
                        ? 'font-normal text-muted-foreground cursor-not-allowed'
                        : 'font-normal cursor-pointer'
                    }
                  >
                    {t('featuredImage')}
                    <span className="ms-1.5 text-xs text-muted-foreground">
                      {t('onlyOne')}
                    </span>
                  </FormLabel>
                </FormItem>
              )}
            />
          </div>
        )}
        {type === 'text' && (
          <TextModeSwitches
            value={textMode}
            onChange={next => form.setValue('textMode', next)}
          />
        )}
        {type === 'url' && (
          <UrlModeSwitches
            value={urlMode}
            onChange={next => form.setValue('urlMode', next)}
          />
        )}
        {type === 'select' && (
          <FormField
            control={form.control}
            name="choices"
            render={({ field }) => (
              <FormItem className="sm:col-span-2">
                <FormLabel>{t('choices')}</FormLabel>
                <FormControl>
                  <Textarea
                    {...field}
                    value={field.value ?? ''}
                    rows={3}
                    placeholder={t('choicesPlaceholder')}
                  />
                </FormControl>
                <FormMessage />
              </FormItem>
            )}
          />
        )}
        {type === 'relation' && (
          <FormField
            control={form.control}
            name="relationCollectionId"
            render={({ field }) => (
              <FormItem className="sm:col-span-2">
                <FormLabel>{t('linksTo')}</FormLabel>
                <Select value={field.value ?? ''} onValueChange={field.onChange}>
                  <FormControl>
                    <SelectTrigger className="w-full">
                      <SelectValue
                        placeholder={
                          postTypes.length
                            ? t('pickPostType')
                            : t('createAnotherFirst')
                        }
                      />
                    </SelectTrigger>
                  </FormControl>
                  <SelectContent>
                    {postTypes.map(pt => (
                      <SelectItem key={pt.id} value={pt.id}>
                        {pt.name}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
                <FormMessage />
              </FormItem>
            )}
          />
        )}
        <div className="sm:col-span-2">
          <Button type="submit" disabled={isPending}>
            {isPending ? t('adding') : t('add')}
          </Button>
          {error && <p className="mt-2 text-sm text-destructive">{error}</p>}
        </div>
      </form>
    </Form>
  );
}
